import Foundation
import GroveThemesCore

/// Turns keys.toml, this Mac's monitors.toml and aerospace.base.toml into the
/// aerospace.toml AeroSpace reads.
public enum AeroSpaceRenderer {
    public static let header = "# Generated by Grove Keys from keys.toml and monitors.toml in ~/.config/grove-keys, and aerospace.base.toml. Edit those, not this file."

    /// `monitors`: this Mac's workspace → monitor assignments; none, no table.
    public static func render(keys: KeysFile, base: String, monitors: [(workspace: String, target: String)]) -> String {
        var out = header + "\n\n" + base
        if !out.hasSuffix("\n") { out += "\n" }
        for mode in keys.modes {
            out += "\n[mode.\(TomlDocument.headerPart(mode.name, first: false)).binding]\n"
            for b in mode.bindings {
                out += TomlDocument.keyText(expand(b.key)) + " = " + TomlDocument.valueText(b.value) + "\n"
            }
        }
        if !monitors.isEmpty {
            out += "\n[workspace-to-monitor-force-assignment]\n"
            for m in monitors {
                out += TomlDocument.keyText(m.workspace) + " = " + TomlDocument.valueText(.string(m.target)) + "\n"
            }
        }
        return out
    }

    /// `hyper-` means all four modifiers.
    static func expand(_ key: String) -> String {
        key.hasPrefix("hyper-") ? "cmd-ctrl-alt-shift-" + key.dropFirst("hyper-".count) : key
    }
}
