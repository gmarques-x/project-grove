import Testing
@testable import GroveKeysCore

@Suite struct AeroSpaceRendererTests {
    static let host = "Gustavos-MacBook-Air"

    func rendered() throws -> String {
        let keys = try KeysFile(text: try fixture("keys.toml"))
        return AeroSpaceRenderer.render(keys: keys, base: try fixture("aerospace.base.toml"), host: Self.host)
    }

    /// The parser has no dotted keys or `[[tables]]`, which the base file uses,
    /// so the mode tables are cut out of today's file by text and parsed alone;
    /// every other line of today's file must survive into the render.
    @Test func rendersTodaysBindings() throws {
        let beforeText = try fixture("aerospace-before.toml")
        let start = try #require(beforeText.range(of: "[mode.main.binding]"))
        let end = try #require(beforeText.range(of: "# Floating apps"))
        let modeText = String(beforeText[start.lowerBound..<end.lowerBound])
        // The top comment block (four lines) is reworded on purpose.
        let top = beforeText.split(separator: "\n", omittingEmptySubsequences: false).prefix(4).joined(separator: "\n")
        let outside = String(beforeText[..<start.lowerBound]).dropFirst(top.count) + String(beforeText[end.lowerBound...])

        let render = try rendered()
        let before = try TomlDocument.parse(modeText)
        let renderModes = render.components(separatedBy: "\n[mode.").dropFirst().map { "[mode." + $0 }.joined(separator: "\n")
        let renderModeText = renderModes.components(separatedBy: "\n[workspace-to-monitor").first ?? ""
        let after = try TomlDocument.parse(renderModeText)
        for mode in ["main", "service"] {
            let b = before.section(["mode", mode, "binding"])?.entries.map { "\($0.key)=\($0.value)" }
            let a = after.section(["mode", mode, "binding"])?.entries.map { "\($0.key)=\($0.value)" }
            #expect(b != nil && b == a, "mode \(mode)")
        }

        let renderLines = Set(render.split(separator: "\n").map(String.init))
        for line in outside.split(separator: "\n") where !line.isEmpty {
            #expect(renderLines.contains(String(line)), "\(line)")
        }
    }

    @Test func expandsHyper() throws {
        var keys = try KeysFile(text: "[aerospace.main]\n")
        keys.setBinding(mode: "main", key: "hyper-1", value: .string("workspace 1"))
        let out = AeroSpaceRenderer.render(keys: keys, base: "", host: Self.host)
        #expect(out.contains("cmd-ctrl-alt-shift-1 = 'workspace 1'") || out.contains("cmd-ctrl-alt-shift-1 = \"workspace 1\""))
        #expect(!out.contains("hyper-"))
    }

    @Test func monitorsForThisHostOnly() throws {
        var keys = try KeysFile(text: "")
        keys.setMonitor(host: "A", workspace: "1", target: "secondary")
        keys.setMonitor(host: "B", workspace: "2", target: "main")
        let a = AeroSpaceRenderer.render(keys: keys, base: "", host: "A")
        #expect(a.contains("[workspace-to-monitor-force-assignment]"))
        #expect(a.contains("\"1\" = \"secondary\""))
        #expect(!a.contains("\"2\""))
        let c = AeroSpaceRenderer.render(keys: keys, base: "", host: "C")
        #expect(!c.contains("workspace-to-monitor-force-assignment"))
    }

    @Test func startsWithHeader() throws {
        let out = try rendered()
        #expect(out.hasPrefix(AeroSpaceRenderer.header + "\n\n"))
        #expect(AeroSpaceRenderer.header == "# Generated by Grove Keys from ~/.config/grove-keys/keys.toml and aerospace.base.toml. Edit those, not this file.")
    }
}
